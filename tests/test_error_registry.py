"""Integrity tests for the vendored error catalog.

``dashscope/_error_registry.py`` is a generated artifact from the
separate ``dashscope-error-registry`` repo (``tools/generate.py`` over
``data/*.textproto``), vendored at ``__version__ == "1.0.11"``. Only the
``PublicError`` and ``SdkErrorDef`` tables are carried; see
``test_vendored_copy_is_pruned_to_the_tables_v2_consumes``.

These tests pin the facts the v2 error layer relies on, so that an
upstream regeneration surfaces as a test failure instead of silent
drift.

Nothing here asserts how ``dashscope/errors.py`` maps the catalog;
that coupling lives in ``tests/test_errors.py``, so this file keeps
depending on the generated artifact alone.
"""

from __future__ import annotations

import dataclasses
import re

import pytest

from dashscope.agentstudio import exceptions as agentstudio_exceptions
from dashscope.finetune.reinforcement.common import errors as rl_errors
from dashscope import _error_registry as registry

PUBLIC = registry.PUBLIC_ERRORS
SDK = registry.SDK_ERRORS

_PLACEHOLDER = re.compile(r"\{(\w+)\}")

# Operation outcomes raised through ``AgenticRLError.from_catalog`` rather
# than dedicated exception classes.
_CONDITION_ONLY = {
    "sdk.agentic_rl.FunctionRegistrationFailed",
    "sdk.agentic_rl.DatasetsUploadFailed",
    "sdk.agentic_rl.DuplicateFunctionNames",
    "sdk.agentic_rl.JobSubmissionFailed",
    "sdk.agentic_rl.WorkflowFailed",
    "sdk.agentic_rl.UnsupportedFunctionType",
    "sdk.agentic_rl.FunctionTestFailed",
    "sdk.agentic_rl.FunctionTestTimeout",
}

# The nine exception class names the catalog requires.
_REQUIRED_CLASSES = {
    "AuthenticationError",
    "BadRequestError",
    "GatewayTimeoutError",
    "InternalServerError",
    "NotFoundError",
    "PermissionDeniedError",
    "RateLimitError",
    "RequestTooLargeError",
    "ServiceUnavailableError",
}


def _classes(module):
    return {
        name
        for name in dir(module)
        if isinstance(getattr(module, name), type)
        and issubclass(getattr(module, name), BaseException)
    }


def _by_name(entries):
    return {entry.name: entry for entry in entries}


def _by_key(key):
    for entry in PUBLIC:
        if entry.key == key:
            return entry
    raise AssertionError(f"no public entry with key {key!r}")


def test_catalog_size_and_provenance():
    assert registry.__version__ == "1.0.11"
    assert registry.__commit__ == "84e5f33"
    assert registry.__snapshot__ is False
    assert len(PUBLIC) == 16
    assert len(SDK) == 41


def test_generated_header_survives_vendoring():
    assert registry.__doc__ == (
        "Auto-generated by tools/generate.py -- DO NOT EDIT."
    )


def test_vendored_copy_is_pruned_to_the_tables_v2_consumes():
    """Upstream 1.0.11 also ships a 299-entry ``INTERNAL_ERRORS`` table.

    It describes server-side components (``gateway.*`` / ``mint.*`` /
    ``api.*`` / ``turbo.*`` / ``model.*``) through ``InternalErrorDef``,
    and its ``cause`` / ``solution`` text is Chinese. A client SDK never
    raises any of them, so the table is deliberately not vendored.

    Pinned so the omission stays a recorded decision instead of looking
    like a copying accident -- and so that anyone who later vendors the
    full artifact has to update this test on purpose.
    """
    assert not hasattr(registry, "InternalErrorDef")
    assert not hasattr(registry, "INTERNAL_ERRORS")


def test_public_entries_well_formed():
    keys = set()
    for entry in PUBLIC:
        assert entry.key, entry
        assert entry.key not in keys, f"duplicate key {entry.key}"
        keys.add(entry.key)
        assert isinstance(entry.status_code, int)
        assert 400 <= entry.status_code <= 599, entry
        assert entry.error_code, entry
        assert entry.error_msg, entry
        assert entry.anthropic_error_code, entry


def test_public_entries_are_immutable():
    with pytest.raises(dataclasses.FrozenInstanceError):
        PUBLIC[0].key = "mutated"


def test_catalog_requires_exactly_ten_exception_classes():
    assert {entry.error_code for entry in PUBLIC} == _REQUIRED_CLASSES


def test_catalog_covers_nine_distinct_statuses():
    assert {entry.status_code for entry in PUBLIC} == {
        400,
        401,
        403,
        404,
        413,
        429,
        500,
        503,
        504,
    }


def test_internal_entries_well_formed():
    names = set()
    for entry in SDK:
        assert entry.name.startswith("sdk."), entry
        assert entry.name not in names, f"duplicate name {entry.name}"
        names.add(entry.name)
        assert entry.message, entry
        assert isinstance(entry.solution, str)
        assert isinstance(entry.allow_retry, bool)
        assert all(isinstance(v, str) for v in entry.vars)


def test_function_layer_error_matches_generated_registry_source():
    entry = _by_name(SDK)["sdk.agentic_rl.FunctionLayerError"]
    assert entry.message == "Creating a layer of function failed."
    assert entry.solution == (
        "Failed to create the function dependency layer. Check that the "
        "requirements.txt or setup.py is valid and all dependencies are "
        "installable. Review the layer build logs for details."
    )
    # Python-only runtime controls belong at the raise site, not in the
    # cross-language generated catalog.
    assert "FC_LAYER_STATUS_TIMEOUT" not in entry.solution


def test_internal_vars_match_message_placeholders():
    """Every declared var is used, and every placeholder is declared."""
    for entry in SDK:
        used = set(_PLACEHOLDER.findall(entry.message))
        assert used == set(entry.vars), entry.name


def test_public_placeholders_are_undeclared():
    """``PublicError`` has no ``vars`` field, unlike ``SdkErrorDef``.

    Pinned because it means the public side cannot be validated the way
    the sdk side is: a caller filling ``{parameter}`` has to discover the
    name by reading ``error_msg``.
    """
    assert not hasattr(PUBLIC[0], "vars")
    with_placeholders = {
        entry.key: sorted(set(_PLACEHOLDER.findall(entry.error_msg)))
        for entry in PUBLIC
        if _PLACEHOLDER.search(entry.error_msg)
    }
    assert with_placeholders == {
        "missing_parameter": ["parameter"],
        "resource_not_found": ["resource"],
        "request_too_large": ["limit"],
    }


def test_format_msg_substitution():
    entry = _by_key("missing_parameter")
    assert entry.format_msg({"parameter": "model"}) == (
        "Missing required parameter: model."
    )


def test_format_msg_leaves_unfilled_placeholder_intact():
    """An unfilled variable must stay visible, never be dropped."""
    entry = _by_key("missing_parameter")
    raw = "Missing required parameter: {parameter}."
    assert entry.format_msg() == raw
    assert entry.format_msg(None) == raw
    assert entry.format_msg({}) == raw
    assert entry.format_msg({"other": "x"}) == raw


def test_format_msg_ignores_unknown_substitutions():
    entry = _by_key("request_too_large")
    assert entry.format_msg({"limit": "10MB", "zz": "q"}).endswith("10MB.")


def test_format_message_substitution():
    entry = _by_name(SDK)["sdk.agentic_rl.FunctionRegistrationFailed"]
    assert entry.format_message({"inner_code": "4011"}) == (
        "Function component registration failed: 4011."
    )
    assert entry.format_message() == entry.message


def test_agentic_rl_reachability_counts():
    """18 dedicated classes, plus condition-only and base-class entries."""
    rl = _classes(rl_errors)
    entries = [e for e in SDK if e.name.startswith("sdk.agentic_rl.")]
    assert len(entries) == 27

    suffixes = {e.name.rsplit(".", 1)[1] for e in entries}
    exact = suffixes & rl
    assert len(exact) == 18, sorted(exact)

    assert "sdk.agentic_rl.Error" in _by_name(SDK)

    without_dedicated_classes = suffixes - rl
    expected = {name.rsplit(".", 1)[1] for name in _CONDITION_ONLY}
    expected.add("Error")
    assert without_dedicated_classes == expected


def test_every_1x_rl_exception_has_a_catalog_landing_point():
    """The direction that matters: no 1.x class is left unmapped.

    ``AgenticRLError`` is the base class the catalog spells
    ``sdk.agentic_rl.Error``; everything else matches by class name.
    """
    names = _by_name(SDK)
    local_classes = {
        name
        for name in _classes(rl_errors)
        if getattr(rl_errors, name).__module__ == rl_errors.__name__
    }
    for cls_name in local_classes:
        candidate = f"sdk.agentic_rl.{cls_name}"
        assert candidate in names or cls_name == "AgenticRLError", cls_name
    assert "sdk.agentic_rl.Error" in names


def test_agentstudio_sdk_error_entries_have_native_classes():
    """The catalog's four AgentStudio entries all have native classes."""
    expected = {
        "APIConnectionError",
        "APITimeoutError",
        "StreamError",
        "StreamClosedError",
    }
    entries = [e for e in SDK if e.name.startswith("sdk.agentstudio.")]
    assert {e.name.rsplit(".", 1)[1] for e in entries} == expected
    assert expected <= _classes(agentstudio_exceptions)


def test_agentstudio_has_no_family_fallback():
    """AgentStudio HTTP errors use statuses, not a generic SDK entry."""
    assert "sdk.agentstudio.Error" not in _by_name(SDK)
    status_classes = {
        name
        for name in _classes(agentstudio_exceptions)
        if issubclass(
            getattr(agentstudio_exceptions, name),
            agentstudio_exceptions.APIStatusError,
        )
    }
    catalogued = {
        e.name.rsplit(".", 1)[1]
        for e in SDK
        if e.name.startswith("sdk.agentstudio.")
    }
    assert status_classes.isdisjoint(catalogued)
    assert status_classes, "expected 1.x agentstudio HTTP error classes"


def test_unfamily_entries_are_the_generic_sdk_ones():
    """Entries outside a product family are the cross-SDK generics.

    ``sdk.InvalidApiKey`` plus the transport/file quartet shared with
    the Java SDK (Python wires up ConnectionError / Timeout / IoError;
    ConnectionInterrupted is a Java threading artifact carried for
    parity). Anything else landing here means a product family grew
    without its ``sdk.<family>.`` prefix -- that is a catalog bug.
    """
    others = [
        e.name
        for e in SDK
        if not e.name.startswith(
            ("sdk.agentic_rl.", "sdk.agentstudio.", "sdk.ws."),
        )
    ]
    assert others == [
        "sdk.InvalidApiKey",
        "sdk.ConnectionError",
        "sdk.ConnectionInterrupted",
        "sdk.Timeout",
        "sdk.IoError",
    ]


def test_ws_family_entries():
    """The five websocket entries; four wired, one carried for parity.

    ProtocolError / IllegalState / QueueCapacityExceeded /
    BinaryOwnerConflict back the v2 websocket transport's exception classes.
    UpstreamQueueFull remains parity-only because sends are synchronous and
    the Python transport has no upstream queue.
    """
    entries = _by_name(SDK)
    expected = {
        "sdk.ws.ProtocolError",
        "sdk.ws.UpstreamQueueFull",
        "sdk.ws.QueueCapacityExceeded",
        "sdk.ws.BinaryOwnerConflict",
        "sdk.ws.IllegalState",
    }
    assert {e.name for e in SDK if e.name.startswith("sdk.ws.")} == expected

    from dashscope import errors as v2_errors

    wired = {
        "sdk.ws.ProtocolError": "WsEventError",
        "sdk.ws.IllegalState": "WsStateError",
        "sdk.ws.QueueCapacityExceeded": ("WsQueueCapacityExceededError"),
        "sdk.ws.BinaryOwnerConflict": "WsBinaryOwnerConflictError",
    }
    for name, cls_name in wired.items():
        cls = getattr(v2_errors, cls_name)
        assert cls._SDK_ERROR_NAME == name
        expected_vars = (
            []
            if name.endswith("QueueCapacityExceeded")
            else [
                "detail",
            ]
        )
        assert entries[name].vars == expected_vars
